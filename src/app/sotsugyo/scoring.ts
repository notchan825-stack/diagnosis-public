export interface Tier {
  label: string;
  message: string;
  urgent: boolean;
}

export function tier(count: number): Tier {
  if (count <= 4)
    return {
      label: "基盤はできています",
      message:
        "事業の土台は整っています。次のステージへ行くための「ひと押し」——絞り込みと見せ方の設計だけが残っています。",
      urgent: false,
    };
  if (count <= 9)
    return {
      label: "今が転換点です",
      message:
        "がんばりが空回りし始める時期です。仕組を作る前に、まず「設計」——誰に・何を・なぜあなたから、の言語化が必要です。",
      urgent: true,
    };
  return {
    label: "一人で抱えすぎています",
    message:
      "このままでは数年後も同じ場所にいる可能性が高い状態です。足りないのは頑張りではなく、コンセプト・仕組・見せ方の設計です。早急に動きましょう。",
    urgent: true,
  };
}

